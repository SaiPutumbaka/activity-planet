import { fileURLToPath } from "node:url";
import { defineConfig, loadEnv, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { tanstackRouter } from "@tanstack/router-plugin/vite";
import { VitePWA } from "vite-plugin-pwa";

/**
 * Image sources (security review, migration 22), as a CSP meta tag so it also holds inside the
 * bundled Capacitor app, where vercel.json headers never apply. The database accepts only
 * own-storage URLs for avatars and human-made covers; imported events keep their feeds' own
 * https covers (D-037), so those image hosts are listed too. The map tile host is OpenFreeMap
 * (D-038). Only img-src is set. Keep this list in step with apps/web/next.config.ts.
 */
const IMPORTED_IMAGE_HOSTS = [
  "https://localist-images.azureedge.net", // GSU Localist
  "https://se-images.campuslabs.com", // PIN (Campus Labs Engage)
];
const MAP_TILE_HOST = "https://tiles.openfreemap.org";

function imageCsp(supabaseUrl: string | undefined): Plugin {
  // This project's Storage origin; any Supabase project host only if the build has no URL.
  let storage = "https://*.supabase.co";
  try {
    if (supabaseUrl) storage = new URL(supabaseUrl).origin;
  } catch {
    /* keep the fallback */
  }
  const sources = ["'self'", "data:", "blob:", storage, MAP_TILE_HOST, ...IMPORTED_IMAGE_HOSTS]
    .filter(Boolean)
    .join(" ");
  return {
    name: "ap-image-csp",
    transformIndexHtml: () => [
      {
        tag: "meta",
        attrs: { "http-equiv": "Content-Security-Policy", content: `img-src ${sources}` },
        injectTo: "head-prepend",
      },
    ],
  };
}

export default defineConfig(({ mode }) => ({
  plugins: [
    imageCsp(
      loadEnv(mode, fileURLToPath(new URL(".", import.meta.url)), "VITE_").VITE_SUPABASE_URL,
    ),
    // Order matters: the router plugin must run before React.
    tanstackRouter({ target: "react", autoCodeSplitting: true }),
    react(),
    tailwindcss(),
    VitePWA({
      registerType: "autoUpdate",
      includeAssets: ["icon.svg", "icons/apple-touch-icon.png"],
      manifest: {
        name: "Activity Planet",
        short_name: "Activity Planet",
        description: "Find your people and something to do with them this week.",
        start_url: "/",
        scope: "/",
        display: "standalone",
        orientation: "portrait",
        background_color: "#ffffff",
        theme_color: "#ffffff",
        categories: ["social", "lifestyle", "sports"],
        // Generated by scripts/gen-icons.mts from packages/ui/src/brand/scene.ts.
        icons: [
          { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
          { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
          {
            src: "/icons/icon-maskable-512.png",
            sizes: "512x512",
            type: "image/png",
            purpose: "maskable",
          },
        ],
      },
      workbox: {
        navigateFallback: "/index.html",
        navigateFallbackDenylist: [/^\/api\//],
        globPatterns: ["**/*.{js,css,html,svg,png,woff2}"],
        // MapLibre (about 270 KB gzip) is lazy-loaded on the Map tab only (D-038). Keep it out of
        // the install-time precache so people who never open the map never download it; it is
        // cached on first use instead (hashed file names, so cache-first is safe).
        globIgnores: ["**/map-canvas-*.{js,css}"],
        runtimeCaching: [
          {
            urlPattern: ({ url }) =>
              url.origin === self.location.origin && /\/assets\/map-canvas-/.test(url.pathname),
            handler: "CacheFirst",
            options: { cacheName: "map-canvas", expiration: { maxEntries: 4 } },
          },
          // Static place tile files (D-042 slice 5, lib/place-files.ts): the names carry a content
          // hash, so a cached file is never stale. GitHub Pages sends max-age=600 and cannot be
          // told otherwise; this keeps them cache-first on the device for 60 days instead.
          {
            urlPattern: ({ url }) =>
              /\/places\/v\d+\/\d+\.[0-9a-f]{16}\.json\.gz$|\/rules\/v\d+\.[0-9a-f]{16}\.json\.gz$/.test(
                url.pathname,
              ),
            handler: "CacheFirst",
            options: {
              cacheName: "place-files",
              expiration: { maxEntries: 60, maxAgeSeconds: 60 * 60 * 24 * 60 },
              cacheableResponse: { statuses: [200] },
            },
          },
          {
            urlPattern: /^https:\/\/fonts\.googleapis\.com\/.*/i,
            handler: "StaleWhileRevalidate",
            options: { cacheName: "google-fonts-stylesheets" },
          },
          {
            urlPattern: /^https:\/\/fonts\.gstatic\.com\/.*/i,
            handler: "CacheFirst",
            options: {
              cacheName: "google-fonts-webfonts",
              expiration: { maxEntries: 12, maxAgeSeconds: 60 * 60 * 24 * 365 },
            },
          },
        ],
      },
    }),
  ],
  resolve: { alias: { "@": fileURLToPath(new URL("./src", import.meta.url)) } },
  server: { port: 3001 },
  build: { sourcemap: true },
}));
